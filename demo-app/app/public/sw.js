// The app's service worker.
//
// Scope: '/' — registered from main.jsx with `{ scope: '/' }`. Two jobs, hand-rolled (no
// Workbox) because the surface is small and a caching layer must never mask a bug:
//   1. push notifications and their click-through;
//   2. 🔴 OFFLINE (CS-665): keep the app's shell and the crew's screens on the phone, so a
//      cleaner who loses signal (a basement, a dead zone) can still open a clean, its
//      checklist and its clock-out — and can start the installed app with no signal at all.
//
// HOW THE OFFLINE CACHE WORKS. Each build writes its id, its entry script and the list of
// files to keep into the three GENERATED lines below (vite-plugins/sw-precache.mjs, a Vite plugin
// run by vite.config.js). Installing a build's worker keeps that list ONCE: a hashed build
// file the phone already holds from an earlier build is copied, not downloaded again, and the
// saved page must be THIS build's (a deploy landing mid-install would otherwise pair a new
// page with old scripts — the install then fails and the worker already on the phone stays).
// Activating it drops every older build's cache, so the phone holds one build at a time.
//   · a PAGE (a navigation): the network first, so a deploy reaches the phone at once; with no
//     answer (offline, or nothing within NAV_TIMEOUT_MS) the kept page, and the app boots from
//     the phone and reads its own data the way it always has offline.
//   · a hashed BUILD FILE (/assets/*): the phone's copy first (a hashed name never changes
//     content), else the network, kept for next time. Never fetched and no signal: it fails,
//     and the app says that screen opens when the signal is back (lib/staleBuild).
//   · /api, any other site, anything but GET: untouched, straight to the network.
// In the dev server the GENERATED lines keep their defaults: nothing is cached or answered.

const APP_NAME = "PolishPoint"; // GENERATED by `npm --prefix app run brand` from the brand file
const ICON = '/icon-192.png';
const BADGE = '/icon-192.png';

// GENERATED at build time by vite-plugins/sw-precache.mjs. These defaults mean "the dev server".
const BUILD_ID = 'dev';
const SHELL_ENTRY = '';
const PRECACHE = [];

const OFFLINE = BUILD_ID !== 'dev';
const CACHE_PREFIX = 'app-offline-';
const CACHE = `${CACHE_PREFIX}${BUILD_ID}`;
const SHELL = '/index.html';
// A page request that has not answered in this long is answered from the phone instead: a
// weak signal must not hold a cleaner on a white screen. The next page load tries again.
const NAV_TIMEOUT_MS = 6000;
const KEEP_IN_PARALLEL = 6;
const isBuildFile = (pathname) => pathname.startsWith('/assets/');

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    if (OFFLINE) await keepThisBuild();
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  if (!OFFLINE) return;
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (isBuildFile(url.pathname)) { event.respondWith(fromPhoneElseNetwork(event)); return; }
  if (req.mode === 'navigate') { event.respondWith(fromNetworkElsePhone(req)); return; }
  if (PRECACHE.includes(url.pathname)) event.respondWith(fromPhoneElseNetwork(event));
});

// The page first — and only if it is this build's — then everything on the list.
async function keepThisBuild() {
  const cache = await caches.open(CACHE);
  const page = await fetch(SHELL, { cache: 'no-cache' });
  if (!page.ok) throw new Error(`offline cache: the app page answered ${page.status}`);
  const html = await page.clone().text();
  if (SHELL_ENTRY && !html.includes(SHELL_ENTRY)) throw new Error('offline cache: the app page belongs to another build');
  await cache.put(SHELL, await withoutRedirect(page));
  const todo = PRECACHE.filter((p) => p !== SHELL);
  for (let i = 0; i < todo.length; i += KEEP_IN_PARALLEL) {
    await Promise.all(todo.slice(i, i + KEEP_IN_PARALLEL).map((p) => keepOne(cache, p)));
  }
}

async function keepOne(cache, pathname) {
  if (await cache.match(pathname)) return;
  // A hashed build file never changes content, so a copy an earlier build kept IS this file.
  // Anything else (the icons, the manifest) is fetched fresh, so a new logo reaches the phone.
  const earlier = isBuildFile(pathname) ? await caches.match(pathname) : null;
  const res = earlier || await fetch(pathname, { cache: isBuildFile(pathname) ? 'default' : 'no-cache' });
  if (!res || !res.ok) throw new Error(`offline cache: ${pathname} answered ${res ? res.status : 'nothing'}`);
  await cache.put(pathname, res);
}

// Safari will not use a redirected response for a page, so a kept page is stored plain.
async function withoutRedirect(res) {
  if (!res.redirected) return res;
  return new Response(await res.blob(), { status: res.status, statusText: res.statusText, headers: res.headers });
}

async function fromPhoneElseNetwork(event) {
  const req = event.request;
  const kept = await caches.match(req);
  if (kept) return kept;
  const res = await fetch(req);
  if (res.ok && res.type !== 'opaque') {
    const copy = res.clone();
    event.waitUntil(caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {}));
  }
  return res;
}

async function fromNetworkElsePhone(req) {
  const kept = await (await caches.open(CACHE)).match(SHELL);
  if (!kept) return fetch(req);
  let timer = null;
  const tooSlow = new Promise((resolve) => { timer = setTimeout(() => resolve(null), NAV_TIMEOUT_MS); });
  try {
    return (await Promise.race([fetch(req), tooSlow])) || kept;
  } catch {
    return kept;
  } finally {
    clearTimeout(timer);
  }
}

// `push` is fired by the browser/OS when the push service receives a payload
// from our backend. Payload shape: { title, body, url, tag }.
self.addEventListener('push', (event) => {
  let data = {};
  try {
    data = event.data ? event.data.json() : {};
  } catch {
    data = { title: APP_NAME, body: event.data?.text?.() || '' };
  }
  const title = data.title || APP_NAME;
  const options = {
    body: data.body || '',
    icon: data.icon || ICON,
    badge: data.badge || BADGE,
    tag: data.tag,             // collapses repeats from the same source
    data: { url: data.url || '/' },
  };
  event.waitUntil(self.registration.showNotification(title, options));
});

// Click handler: focus an existing app window if one is open, otherwise open
// a fresh client at the URL the push payload provided.
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const targetUrl = event.notification.data?.url || '/';
  event.waitUntil(
    (async () => {
      const clientList = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
      for (const client of clientList) {
        if ('focus' in client) {
          await client.navigate(targetUrl).catch(() => {});
          return client.focus();
        }
      }
      if (self.clients.openWindow) {
        return self.clients.openWindow(targetUrl);
      }
      return null;
    })()
  );
});
