#!/usr/bin/env node
// code-sweep-ledger.mjs — the P0 "every line" code-sweep enumerator (DEV_PLAYBOOK 2.0.1).
//
// Offline and READ-ONLY on the repo. It enumerates the source universe, records each
// file's line count and blob SHA, assigns each an owning phase by the path rule table
// below (first match wins), and merges the result into docs/playbook/CODE_SWEEP_LEDGER.md
// WITHOUT dropping existing review rows. It never touches the network or a live service.
//
//   node scripts/code-sweep-ledger.mjs                 # dry run: print the counts, write nothing
//   node scripts/code-sweep-ledger.mjs --write         # (re)generate the ledger, preserving reviews
//   node scripts/code-sweep-ledger.mjs --check <phase> # exit 1 if a file that phase owns has no
//                                                       # review row at its current blob, or any
//                                                       # universe file matches no rule
//   node scripts/code-sweep-ledger.mjs --out <path>    # write target (default docs/playbook/CODE_SWEEP_LEDGER.md)
//
// THE RULE TABLE IN THIS FILE IS THE AUTHORITY (2.0.1). The table in DEV_PLAYBOOK 2.0.1
// documents it. The one axis a human sets is the P4 `app/src/lib` list (P0 step 7): the
// data/sync/money/time lib files. Everything else is a path glob.
//
// The ledger is a SHARED record written by the orchestrator; a `cs-builder` run leaves it
// uncommitted. This script only builds it.
