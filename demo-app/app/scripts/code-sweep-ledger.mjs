// ── the ownership rule table — FIRST MATCH WINS (2.0.1) ───────────────────────
export function ownerPhase(p) {
  // 0. P8 — the hand-authored design-system token source (carved out of the generated mirror,
  //    orchestrator review). Ahead of the design-system EXCLUDE rule.
  if (p === 'app/design-system/tokens.config.json') return 'P8';
  // 1. P8 — every stylesheet under app/src
  if (p.startsWith('app/src/') && p.endsWith('.css')) return 'P8';
  // 2. P2 — tooling, tests, CI, harness config, env, ignore files
  if (matchesP2(p)) return 'P2';
  // 3. P3 — server, migrations, the deploy manifest, client auth
  if (p.startsWith('app/api/')) return 'P3';
  if (p.startsWith('supabase/migrations/')) return 'P3';
  if (p === 'app/vercel.json') return 'P3';
  if (p.startsWith('app/src/auth/')) return 'P3';
  // 4. P4 — the store, plus the explicit data/sync/money/time lib list; a NEW lib
  //    file (in neither lib list) defaults to P4 until reclassified in the table.
  if (p.startsWith('app/src/lib/')) {
    if (LIB_P4.has(p)) return 'P4';
    if (LIB_P5.has(p)) return 'P5';
    return 'P4';
  }
  if (p.startsWith('app/src/store/')) return 'P4';
  // 5. P7 — the perf entry points
  if (p === 'app/src/main.jsx') return 'P7';
  if (p.startsWith('app/public/')) return 'P7';
  if (p === 'app/index.html') return 'P7';
  // 6. P5 — the rest of app/src (pages, components, hooks, layouts, data, brand, App.jsx)
  if (p.startsWith('app/src/')) return 'P5';
  return null; // owned by no rule
}

function matchesP2(p) {
  if (p.startsWith('app/scripts/')) return true;
  if (p.startsWith('.github/')) return true;
  if (p.startsWith('.claude/')) return true;
  if (p.startsWith('app/tests/')) return true;
  if (p === 'app/package.json') return true;
  if (p === 'app/vite.config.js') return true;
  if (p === 'app/eslint.config.js') return true;
  if (/^app\/playwright[^/]*\.config\.js$/.test(p)) return true;
  if (p === 'app/wiring.contract.mjs') return true;
  if (p === 'app/deletion.manifest.json') return true;
  if (/^app\/\.env/.test(p)) return true;         // app/.env*
  if (p === 'app/.vercelignore') return true;
  if (/(^|\/)\.gitignore$/.test(p)) return true;  // **/.gitignore
  if (p === 'supabase/config.toml') return true;
  return false;
}

// ── ledger table parse / build / render ──────────────────────────────────────
const COLS = ['File', 'Lines', 'Phase', 'Reviewed blob', 'Lens', 'Lines read', 'Findings (CS-IDs)', 'Date'];

// Parse the markdown table into Map<path, {lines, phase, reviewedBlob, lens, linesRead, findings, date}>.
export function parseLedgerRows(md) {
  const rows = new Map();
  for (const line of md.split('\n')) {
    if (!line.startsWith('|')) continue;
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length < 8) continue;
    const file = cells[0].replace(/^`|`$/g, '');
    if (file === 'File' || /^-+$/.test(file) || file === '') continue; // header / divider
    rows.set(file, {
      lines: cells[1], phase: cells[2], reviewedBlob: cells[3],
      lens: cells[4], linesRead: cells[5], findings: cells[6], date: cells[7],
    });
  }
  return rows;
}

// Build the rows for a universe [{path, blob, lines}], preserving a review from
// `existing` (Map from parseLedgerRows) only when its reviewedBlob === the current blob.
export function buildLedgerRows(universe, existing = new Map()) {
  return [...universe]
    .sort((a, b) => a.path.localeCompare(b.path))
    .map(({ path: p, blob, lines }) => {
      const phase = ownerPhase(p) || '?';
      const prev = existing.get(p);
      const keep = prev && prev.reviewedBlob && prev.reviewedBlob === blob;
      return {
        path: p,
        lines: String(lines),
        phase,
        reviewedBlob: keep ? prev.reviewedBlob : '',
        lens: keep ? (prev.lens || '') : '',
        linesRead: keep ? (prev.linesRead || '') : '',
        findings: keep ? (prev.findings || '') : '',
        date: keep ? (prev.date || '') : '',
      };
    });
}

export function renderLedger(rows, meta = {}) {
  const head = [
    '# Code sweep ledger (DEV_PLAYBOOK 2.0.1)',
    '',
    '> GENERATED by `app/scripts/code-sweep-ledger.mjs`. Every tracked source file, its owning',
    '> phase and the blob SHA it was last read at in full. A file whose blob changed since its',
    '> review counts as unreviewed again. Reviewers fill the last five columns; the enumerator',
    '> fills File / Lines / Phase. Regenerate with `--write` (existing reviews are preserved).',
    '',
    meta.stamp ? `_Universe at \`${meta.stamp}\`: ${rows.length} files._` : '',
    '',
    `| ${COLS.join(' | ')} |`,
    `|${COLS.map(() => '---').join('|')}|`,
  ].filter((l) => l !== '');
  const body = rows.map((r) => `| ${r.path} | ${r.lines} | ${r.phase} | ${r.reviewedBlob} | ${r.lens} | ${r.linesRead} | ${r.findings} | ${r.date} |`);
  return `${head.join('\n')}\n${body.join('\n')}\n`;
}

// ── --check: does phase <phase> have a current-blob review row for every file it
// owns? A universe file matching no rule (and not EXCLUDE-tabled) also fails. ─────────
export function runCheck(phase, universe, existing = new Map()) {
  const failures = [];
  for (const { path: p, blob } of universe) {
    if (excludeTableReason(p)) continue;
    const owner = ownerPhase(p);
    if (owner === null) {
      failures.push({ path: p, reason: 'matches no rule (no owner) — add a rule or an EXCLUDE entry' });
      continue;
    }
    if (owner !== phase) continue;
    const row = existing.get(p);
    if (!row || !row.reviewedBlob) {
      failures.push({ path: p, reason: 'no review row' });
    } else if (row.reviewedBlob !== blob) {
      failures.push({ path: p, reason: `reviewed at ${row.reviewedBlob}, now ${blob} (changed → unreviewed)` });
    }
  }
  return { failures };
}

// ── git-backed universe (the one impure helper) ──────────────────────────────
function gitUniverse() {
  // `git ls-files -s` → "<mode> <sha> <stage>\t<path>"; the sha IS the blob SHA.
  const out = execFileSync('git', ['ls-files', '-s', '--', ...UNIVERSE_DIRS], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  const universe = [];
  const excluded = [];
  const excludeTable = [];
  for (const line of out.split('\n')) {
    if (!line.trim()) continue;
    const tab = line.indexOf('\t');
    const meta = line.slice(0, tab).split(/\s+/);
    const blob = meta[1];
    const p = line.slice(tab + 1);
    const exReason = isExcludedFromUniverse(p);
    if (exReason) { excluded.push({ path: p, reason: exReason }); continue; }
    const etReason = excludeTableReason(p);
    if (etReason) { excludeTable.push({ path: p, reason: etReason }); continue; }
    const abs = path.join(ROOT, p);
    let lines = 0;
    try { lines = countLines(readFileSync(abs, 'utf8')); } catch { lines = 0; }
    universe.push({ path: p, blob, lines });
  }
  return { universe, excluded, excludeTable };
}

function countLines(s) { // wc -l semantics: count of newline characters
  let n = 0;
  for (let i = 0; i < s.length; i += 1) if (s[i] === '\n') n += 1;
  return n;
}

function headSha() {
  try { return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim(); }
  catch { return 'HEAD'; }
}

// ── CLI ──────────────────────────────────────────────────────────────────────
function main(argv) {
  const args = argv.slice(2);
  const write = args.includes('--write');
  const checkIdx = args.indexOf('--check');
  const outIdx = args.indexOf('--out');
  const outRel = outIdx >= 0 ? args[outIdx + 1] : LEDGER_REL;
  const outAbs = path.isAbsolute(outRel) ? outRel : path.join(ROOT, outRel);

  const { universe, excluded, excludeTable } = gitUniverse();
  const existing = existsSync(outAbs) ? parseLedgerRows(readFileSync(outAbs, 'utf8')) : new Map();

  if (checkIdx >= 0) {
    const phase = args[checkIdx + 1];
    if (!phase) { console.error('--check needs a phase, e.g. --check P4'); process.exit(2); }
    const { failures } = runCheck(phase, universe, existing);
    if (failures.length) {
      console.error(`✗ code-sweep --check ${phase}: ${failures.length} file(s) unreviewed or unowned:`);
      for (const f of failures) console.error(`    ${f.path} — ${f.reason}`);
      process.exit(1);
    }
    console.log(`✓ code-sweep --check ${phase}: every owned file has a review row at its current blob.`);
    return;
  }

  // counts (dry run and write both report them)
  const byPhase = {};
  let unowned = 0;
  for (const u of universe) {
    const ph = ownerPhase(u.path);
    if (ph === null) { unowned += 1; byPhase['(unowned)'] = byPhase['(unowned)'] || { files: 0, lines: 0 }; byPhase['(unowned)'].files += 1; byPhase['(unowned)'].lines += u.lines; continue; }
    byPhase[ph] = byPhase[ph] || { files: 0, lines: 0 };
    byPhase[ph].files += 1;
    byPhase[ph].lines += u.lines;
  }
  const totalLines = universe.reduce((a, u) => a + u.lines, 0);
  const stamp = headSha();

  console.log(`code-sweep-ledger @ ${stamp}`);
  console.log(`  universe: ${universe.length} files, ${totalLines} lines`);
  for (const ph of ['P2', 'P3', 'P4', 'P5', 'P7', 'P8', '(unowned)']) {
    if (byPhase[ph]) console.log(`    ${ph.padEnd(9)} ${String(byPhase[ph].files).padStart(4)} files  ${String(byPhase[ph].lines).padStart(7)} lines`);
  }
  console.log(`  universe-excluded (images/fonts/*.md/screenshots/lockfile/*.baseline.json): ${excluded.length}`);
  console.log(`  EXCLUDE table (owned by no rule, excused): ${excludeTable.length}`);
  for (const e of excludeTable.slice(0, 3)) console.log(`      e.g. ${e.path}`);
  if (unowned) {
    console.error(`✗ ${unowned} file(s) match no rule and are not EXCLUDE-tabled — extend the rule table or EXCLUDE them:`);
    for (const u of universe) if (ownerPhase(u.path) === null) console.error(`      ${u.path}`);
    process.exit(1);
  }

  if (write) {
    const rows = buildLedgerRows(universe, existing);
    writeFileSync(outAbs, renderLedger(rows, { stamp }));
    const reviewed = rows.filter((r) => r.reviewedBlob).length;
    console.log(`  wrote ${outRel}: ${rows.length} rows (${reviewed} carry a preserved review).`);
  } else {
    console.log('  (dry run — pass --write to (re)generate the ledger)');
  }
}

