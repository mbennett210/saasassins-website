// ── universe exclusions: the "minus" in the 2.0.1 universe definition ─────────
// images, fonts, *.md, the visual screenshot baselines, the npm lockfile and the
// generated *.baseline.json files. Docs (*.md, incl. app/src/*.md and supabase/SECURITY.md)
// are owned by the P2 docs finder / Part 3.11, not this ledger.
export const EXCLUDE_EXT = new Set([
  'png', 'jpg', 'jpeg', 'gif', 'svg', 'ico', 'webp', 'avif', 'bmp', // images
  'woff', 'woff2', 'ttf', 'otf', 'eot',                             // fonts
]);
export function isExcludedFromUniverse(p) {
  const dot = p.lastIndexOf('.');
  const ext = dot >= 0 ? p.slice(dot + 1).toLowerCase() : '';
  if (EXCLUDE_EXT.has(ext)) return 'binary asset (image/font)';
  if (p.endsWith('.md')) return 'doc (*.md) — owned by the P2 docs finder / Part 3.11';
  if (p.startsWith('app/tests/visual/__screenshots__/')) return 'visual screenshot baseline';
  if (p === 'app/package-lock.json') return 'npm lockfile';
  if (p.endsWith('.baseline.json')) return 'generated lint baseline';
  return null;
}

